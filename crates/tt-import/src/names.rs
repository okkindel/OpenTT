/// The snake_case form of a field name of the install (`lightBoost` →
/// `light_boost`).
pub fn snake_case(name: &str) -> String {
    let mut out = String::new();
    let mut prev: Option<char> = None;
    for c in name.chars() {
        if c.is_ascii_uppercase() && prev.is_some_and(|p| p.is_ascii_lowercase() || p.is_ascii_digit()) {
            out.push('_');
        }
        out.push(c.to_ascii_lowercase());
        prev = Some(c);
    }
    out
}

/// Our class for a class name of the install.
pub fn class(name: &str) -> String {
    CLASSES.iter().find(|(o, _)| o.eq_ignore_ascii_case(name)).map_or_else(|| name.to_string(), |(_, n)| n.to_string())
}

/// Our name of the install's field `name` of our class `class`.
pub fn field(class: &str, name: &str) -> String {
    FIELDS.iter().find(|(c, o, _)| c.eq_ignore_ascii_case(class) && o.eq_ignore_ascii_case(name)).map_or_else(|| snake_case(name), |(_, _, n)| n.to_string())
}

/// The mixer channel name of a sound description's channel
/// variable.
pub fn channel(variable: &str) -> Option<&'static str> {
    Some(match variable.trim_start_matches('$').to_ascii_lowercase().as_str() {
        "defaultaudiotype" => "default",
        "guiaudiotype" => "gui",
        "simaudiotype" => "sim",
        "messageaudiotype" => "message",
        "musicaudiotype" => "music",
        _ => return None,
    })
}

/// A declaration's class and fields (the install's names) in our names. A field set
/// to a variable must be a sound channel.
pub fn translate(install_class: &str, fields: &[ScriptField]) -> Result<(String, Vec<Field>), String> {
    let class = class(install_class);
    let mut out = Vec::new();
    for f in fields {
        let value = match &f.value {
            ScriptValue::Text(t) => t.clone(),
            ScriptValue::Variable(v) => channel(v).ok_or_else(|| format!("{install_class}.{}: the variable {v} is not supported", f.name))?.to_string(),
        };
        out.push(Field::new(field(&class, &f.name), f.index.clone(), value));
    }
    Ok((class, out))
}

